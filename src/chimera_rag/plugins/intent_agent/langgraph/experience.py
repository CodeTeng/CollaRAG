"""Helpers bridging innovation #2c experiential memory into the 2b retriever.

Two pure functions keep the retriever thin and keep all "experience shaping"
logic testable in isolation:

* :func:`render_experience_hint` — turn recalled entries into a single
  ``SystemMessage`` content string injected at the graph entry (recall).
* :func:`build_experience_entry` — distil one ``ExperienceEntry`` from a
  finished run's state + merged result (write-back), classifying it as a
  ``success`` or a ``lesson`` by the same quality threshold 2b already uses.

Lesson text is generated by a deterministic rule template (no LLM call) so
the whole path stays runnable under MockProvider with zero API key.
"""

from __future__ import annotations

from datetime import UTC, datetime

from chimera_rag.core.types import RetrievalResult
from chimera_rag.interfaces.experiential_memory import ExperienceEntry

# Per-intent capability hints used when generating avoidance lessons. Kept in
# sync with the intent taxonomy and the strategies each intent benefits from.
_INTENT_RECOMMENDED_CAPABILITY: dict[str, str] = {
    "factual": "vector_search",
    "analytical": "multi_hop_retrieve",
    "comparative": "parallel_retrieve",
    "multi_hop": "graph_neighbors / multi_hop_retrieve",
    "exploratory": "graph_neighbors",
    "follow_up": "vector_search (with session context)",
}


def render_experience_hint(entries: list[ExperienceEntry]) -> str | None:
    """Render recalled experiences into a hint string, or None if empty."""
    if not entries:
        return None

    lines = ["历史上同类问题的检索经验（仅供参考，可自主决策）："]
    for entry in entries:
        seq = " → ".join(entry.tool_sequence) if entry.tool_sequence else "(无工具调用)"
        if entry.outcome == "success":
            lines.append(f"  ✅ 成功路径(quality {entry.final_quality:.2f}): {seq}")
        else:
            lesson = entry.lesson or f"路径 {seq} 质量不足"
            lines.append(f"  ⚠️ 规避教训: {lesson}")
    lines.append("请优先参考成功路径，避免已知的低效做法。")
    return "\n".join(lines)


def _make_lesson(intent: str, tool_sequence: list[str], quality: float) -> str:
    seq = " → ".join(tool_sequence) if tool_sequence else "(无工具调用)"
    recommended = _INTENT_RECOMMENDED_CAPABILITY.get(intent, "graph_neighbors")
    return (
        f"intent={intent} 时，工具序列 {seq} 质量仅 {quality:.2f}；"
        f"建议补充 {recommended}"
    )


def build_experience_entry(
    *,
    intent: str,
    query_text: str,
    tool_sequence: list[str],
    iterations: int,
    quality: float,
    result: RetrievalResult,
    quality_threshold: float,
) -> ExperienceEntry:
    """Distil a finished run into one ExperienceEntry, classified by quality.

    ``quality >= quality_threshold`` -> a reusable ``success`` (keeps the QA
    pair); otherwise a ``lesson`` (keeps the avoidance note, drops the answer
    so low-quality answers are never reused).
    """
    now = datetime.now(UTC).isoformat()
    is_success = quality >= quality_threshold

    if is_success:
        answer_text = " ".join(c.text for c in result.chunks) or None
        evidence_ids = [c.chunk_id for c in result.chunks]
        return ExperienceEntry(
            intent=intent,  # type: ignore[arg-type]  validated by pydantic
            query_text=query_text,
            tool_sequence=tool_sequence,
            iterations=iterations,
            final_quality=quality,
            outcome="success",
            lesson=None,
            answer_text=answer_text,
            evidence_chunk_ids=evidence_ids,
            created_at=now,
        )

    return ExperienceEntry(
        intent=intent,  # type: ignore[arg-type]
        query_text=query_text,
        tool_sequence=tool_sequence,
        iterations=iterations,
        final_quality=quality,
        outcome="lesson",
        lesson=_make_lesson(intent, tool_sequence, quality),
        answer_text=None,
        evidence_chunk_ids=[],
        created_at=now,
    )


__all__ = ["build_experience_entry", "render_experience_hint"]
